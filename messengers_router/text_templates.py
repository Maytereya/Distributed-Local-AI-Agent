def basket_total_text(amount: str, *, forks: list[str] | tuple[str, ...] = (), partial: bool = False) -> str:
    """Итог корзины-калькулятора (ТЗ 17.08 §6) — «Итого по прайсу», как в согласованной схеме. Сумму печатает код из прайса
    (`amount` — «1 270 руб.» или «от … до …»). У позиции развилка вариантов — сумма не выдумывается: диапазон и какие позиции
    его дают (решение владельца 22.07: дезинформация ценой хуже уточнения); точную сумму даст список с нужными вариантами —
    его корзина и посчитает."""

    head = "Итого по прайсу за найденные позиции" if partial else "Итого по прайсу"
    if not forks:
        return f"{head}: {amount}"
    named = ", ".join(f"«{fork}»" for fork in forks)
    which = "варианта" if len(forks) == 1 else "вариантов"
    return f"{head}: {amount} — зависит от {which} {named}. Чтобы посчитать точно, пришлите список с нужными вариантами."
