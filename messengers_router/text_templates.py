def price_not_found_text(service: str) -> str:
    """Цены нет: правила и выбор LLM услугу не нашли — честно, без чужой цены (принцип 3)."""

    if not str(service or "").strip():  # фразы услуги нет (цена, этап 2: слова реплики названием не печатаются)
        return "Не нашёл актуальную стоимость. Уточните название услуги или ФИО врача, и я проверю снова."
    return f"Не нашёл актуальную стоимость для «{service}». Уточните название услуги или ФИО врача, и я проверю снова."


def price_names_without_prices_text(service: str, names: list[str] | tuple[str, ...]) -> str:
    """Вариант B политики силы совпадения (L-13, решение владельца 07.10): слабое совпадение, а LLM
    не ответила внятно — названия похожих услуг без цен, выбирает пациент. Названия печатает код из
    прайса (принцип 1); ответ названием на следующем ходу — сильное совпадение, цену покажет код."""

    head = f"По запросу «{service}» нашёл" if str(service or "").strip() else "Нашёл"  # фразы нет — без названия (этап 2)
    if len(names) == 1:
        return f"{head} похожую услугу: «{names[0]}». Если нужна она, напишите её название — подскажу цену."
    lines = "\n".join(f"— {name}" for name in names)
    return f"{head} похожие услуги:\n{lines}\nНапишите, какая из них нужна, — подскажу цену."


# Оговорки под итогом корзины — как в согласованной с заказчиком схеме калькулятора (`docs/BUTTONS_SCHEME_2026-09-17.md`
# §5–§7; ответ заказчика 16.09, п. 2): взятие закрывает и то, что из данных не выводится; скидки в сумму по прайсу не входят.
