"""Видимая деградация данных МИС — ход (д): сбой источника → честный перевод на оператора (решения владельца 08.10, 18.10).

Выключатель `[MESSENGER_ROUTER] mis_honest_degradation = off | on` (по умолчанию off — как было). Под `on`:
- расписание по специальности: не ответил хотя бы один из опрошенных врачей (сбой, таймаут) — перевод
  `service_error_schedule`, как в пути по фамилии; устаревший ответ расписания при сбое не показывается (только живое);
- даты слотов: ни одна дата расписания не разобрана — перевод `service_error_schedule`;
- акции: не загрузились акции или справочник филиалов — «Не получилось загрузить всю информацию об акциях — передаю
  оператору.» и перевод;
- адреса в записи: список врачей пуст (фильтр «где принимает врач» не проверить) — перевод;
- давность прайса и врачей: ≤2 дн. — молча, 3–7 — приписка «по данным на ДД.ММ», >7 или срезов нет — оператор.
Ночью к переводу дописывается часы работы операторов (как у любого перевода, `operator_after_hours_note`).
"""

from __future__ import annotations

from .runtime_config import config as _cfg


def honest() -> bool:
    """Включена ли видимая деградация (`mis_honest_degradation = on`)."""

    return str(getattr(_cfg, "MR_MIS_HONEST_DEGRADATION", "off") or "").strip().lower() == "on"
