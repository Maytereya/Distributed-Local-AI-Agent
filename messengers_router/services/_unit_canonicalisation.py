from ..russian_nlu import normalize_ru

log = logging.getLogger(__name__)


def _normalise(text: str | None) -> str:
    return re.sub(r"\s+", " ", normalize_ru(text)).strip()


# Ключи нормализуем тем же методом, что и lookup-аргументы — чтобы
# вариации регистра/пробелов/тире сопоставлялись корректно.
def _key(name: str) -> str:
    return _normalise(name)


