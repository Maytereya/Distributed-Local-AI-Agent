"""Канонизация имён подразделений (`company_unit_name`) Nayka в набор
канонических специальностей.

## Зачем модуль существует

`unit_links.company_unit_name` приходит из CRM клиники как free-text без
enum'а. Раньше matcher сравнивал эти строки с запросом пациента через
substring/токенизацию. Это приводило к ложным срабатываниям, когда
композитные специальности случайно содержали базовый термин:

- «Врач-мануальный терапевт» матчился на запрос «терапевт»
- «Врач-стоматолог-ортопед» матчился на запрос «ортопед»
- «Врач-пластический хирург» матчился на запрос «хирург»
- «Врач гинеколог-эндокринолог» матчился на запрос «эндокринолог»

Корень в том, что специальность — это **таксономия**, а не bag-of-words.
«Стоматолог-ортопед» — это подвид стоматолога (зубопротезирование),
а не подвид ортопеда (травматология). Подмен здесь НЕ должно быть.

## Как работает

1. Карта `_UNIT_TO_CANONICAL` явно перечисляет все известные unit
   names и сообщает, на какие канонические специальности этот unit
   реально отвечает.
2. `canonicalise_unit(name)` возвращает `frozenset` канонических
   специальностей. Пустой frozenset значит «known unit, не отвечает
   ни на одну специальность» (используется для бэд-данных).
3. Для **неизвестных** unit names функция возвращает `None` —
   сигнал caller-у вернуться к legacy substring-матчеру. Так новые
   врачи в боте начинают работать сразу (без редактирования карты),
   но появляется warning-лог, чтобы поддерживать карту в актуальном
   состоянии.
"""

from __future__ import annotations

