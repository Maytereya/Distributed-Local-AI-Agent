# Нормализованная карта для быстрого lookup.
_UNIT_TO_CANONICAL: dict[str, frozenset[str]] = {
    _key(k): v for k, v in _UNIT_TO_CANONICAL_RAW.items()
}


def canonicalise_unit(unit_name: str) -> frozenset[str] | None:
    """Возвращает набор канонических специальностей для unit name.

    :param unit_name: значение `company_unit_name` из unit_link или
                      элемент `units` legacy-кэша.
    :return:
        - ``frozenset({...})`` — если unit известен карте; набор
          канонических специальностей, которым unit отвечает.
        - ``frozenset()`` — если unit известен карте, но это
          бэд-data / мусор без полезного матча.
        - ``None`` — если unit отсутствует в карте; caller должен
          вернуться к legacy substring-матчеру и залогировать
          warning, чтобы карту пополнили.
    """
    norm = _key(unit_name)
    if not norm:
        return frozenset()
    return _UNIT_TO_CANONICAL.get(norm)


def unit_matches_specialty(unit_name: str, specialty: str) -> bool | None:
    """Проверяет, отвечает ли unit на запрос специальности.

    :param unit_name: имя подразделения врача.
    :param specialty: каноническая специальность пациентского запроса.
    :return:
        - ``True`` — unit известен и отвечает на эту специальность.
        - ``False`` — unit известен, но НЕ отвечает (мусор / другая
          специальность).
        - ``None`` — unit не в карте; caller должен использовать
          legacy substring-fallback.
    """
    canonical = canonicalise_unit(unit_name)
    if canonical is None:
        log.info(
            "unit_canonicalisation_unknown unit=%r — falling back to substring matcher",
            unit_name,
        )
        return None
    spec_norm = _key(specialty)
    if not spec_norm:
        return False
    return spec_norm in {_key(c) for c in canonical}


# Convenience: список «УЗИ-приемлемых» канонических имён для отдельной
# проверки UZI-профиля врача (используется в _matches_uzi_doctor_profile).
_UZI_CANONICAL_LABELS: frozenset[str] = frozenset({"узи"})


def is_uzi_unit(unit_name: str) -> bool | None:
    """Возвращает True/False/None по той же семантике, что
    `unit_matches_specialty`, но специально для УЗИ."""
    canonical = canonicalise_unit(unit_name)
    if canonical is None:
        return None
    return bool({_key(c) for c in canonical} & _UZI_CANONICAL_LABELS)


def known_units_count() -> int:
    """Количество известных карте unit names. Для тестов/диагностики."""
    return len(_UNIT_TO_CANONICAL)


def _all_canonical_targets() -> frozenset[str]:
    """Все канонические значения, фигурирующие в карте.

    Используется тестами для верификации, что мы не привнесли
    специальность, которой нет в `SPECIALTY_CANONICAL`.
    """
    out: set[str] = set()
    for v in _UNIT_TO_CANONICAL.values():
        out.update(_key(c) for c in v)
    return frozenset(out)


def _all_known_unit_keys() -> frozenset[str]:
    """Все нормализованные ключи карты — для тестов."""
    return frozenset(_UNIT_TO_CANONICAL.keys())


